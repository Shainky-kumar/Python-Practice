# data types in python are used to define the type of data that a variable can hold. Python has several built-in data types, including int, float, str, bool, list, tuple, set, and dict. Here are some examples of how to use different data types in Python:


# 1. Integer data type

number = 42
print(number)  # Output: 42
print(type(number))  # Output: <class 'int'>

# 2. Float data type
pi = 3.14
print(pi)  # Output: 3.14
print(type(pi))  # Output: <class 'float'>

# 3. String data type
name = "Python"
print(name)  # Output: Python
print(type(name))  # Output: <class 'str'>

# 4. Boolean data type
is_raining = True
print(is_raining)  # Output: True
print(type(is_raining))  # Output: <class 'bool'>

is_sunny = False
print(is_sunny)  # Output: False
print(type(is_sunny))  # Output: <class 'bool'>

# 5. List data type
fruits = ["apple", "banana", "cherry"]
print(fruits)  # Output: ['apple', 'banana', 'cherry']
print(type(fruits))  # Output: <class 'list'>

# 6. Tuple data type
coordinates = (10, 20)
print(coordinates)  # Output: (10, 20)
print(type(coordinates))  # Output: <class 'tuple'>


# 7. Set data type
unique_numbers = {1, 2, 3, 4, 5}
print(unique_numbers)  # Output: {1, 2, 3, 4
print(type(unique_numbers))  # Output: <class 'set'>

# 8. Dictionary data type
person = {"name": "Alice", "age": 30, "city": "New York"}
print(person)  # Output: {'name': 'Alice', 'age': 30, 'city': 'New York'}
print(type(person))  # Output: <class 'dict'>

# 9. None data type
result = None
print(result)  # Output: None
print(type(result))  # Output: <class 'NoneType'>

# 10. Complex data type
complex_number = 2 + 3j
print(complex_number)  # Output: (2+3j)
print(type(complex_number))  # Output: <class 'complex'>